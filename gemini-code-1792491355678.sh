# 1. Inicializar el repositorio Git
git init

# 2. Añadir el archivo index.html
git add index.html

# 3. Crear el primer commit
git commit -m "Initial commit: Proyecto web Arvanta"

# 4. Cambiar la rama principal a main
git branch -M main

# 5. Enlazar con tu repositorio de GitHub (sustituye la URL por la tuya)
git remote add origin https://github.com/TU-USUARIO/arvanta-inmobiliaria.git

# 6. Subir el código a GitHub
git push -u origin main